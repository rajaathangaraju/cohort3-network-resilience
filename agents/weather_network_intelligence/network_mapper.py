"""Maps validated alerts and inventory IDs to the shared Agent 2 contract."""

from contracts.network_risk_event import AffectedArea, NetworkRiskEvent, WeatherAlertInput

DEFAULT_SYNTHETIC_BOUNDS = AffectedArea(
    south=12.8,
    north=13.2,
    west=77.4,
    east=77.8,
)


def build_network_risk_event(alert: WeatherAlertInput, elements: list[str]) -> NetworkRiskEvent:
    return NetworkRiskEvent(
        schema_version=alert.schema_version,
        team_code=alert.team_code,
        run_id=alert.run_id,
        trace_id=alert.trace_id,
        created_at=alert.created_at,
        data_source=alert.data_source,
        weather_event=alert.weather_event,
        severity=alert.severity,
        affected_region=alert.affected_region,
        forecast=alert.forecast or "Synthetic weather event generated by Agent 1.",
        affected_area=alert.affected_area or DEFAULT_SYNTHETIC_BOUNDS,
        affected_network_elements=elements,
    )
